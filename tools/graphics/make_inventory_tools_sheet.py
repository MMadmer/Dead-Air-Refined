"""Builds the glyphs of the actor menu's sort and filter row (actor_menu_tools.xml).

    python tools/graphics/make_inventory_tools_sheet.py [--preview out.png]

Writes, under packaging/dead-air-x64/compatibility/gamedata:
    textures/ui/ui_da_x64_inv_tools.dds                  512x64 A8R8G8B8, no mips
    configs/ui/textures_descr/ui_da_x64_inv_tools.xml    the ids

White masks with alpha, tinted by the row per button state; the button itself is the game's own
ui_inGame2_inventory_button. RGB stays white where alpha is 0, so filtering never darkens an
edge. Drawn at 4x and filtered down.
"""
import math
import os
import sys

from PIL import Image, ImageDraw

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_xms_pda_sheet import write_dds  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT_ROOT = os.path.join(REPO, "packaging", "dead-air-x64", "compatibility", "gamedata")
CELL = 64
SS = 4
W = CELL * SS

GLYPHS = {}


def glyph(name):
    def reg(fn):
        GLYPHS[name] = fn
        return fn
    return reg


@glyph("sort")
def _sort(d):
    # bars from long to short and an arrow down: "put in order"
    for i, length in enumerate((136, 104, 72)):
        y = 36 + i * 72
        d.rounded_rectangle((20, y, 20 + length, y + 36), radius=10, fill=255)
    d.rectangle((182, 28, 214, 150), fill=255)
    d.polygon([(150, 146), (246, 146), (198, 230)], fill=255)


@glyph("all")
def _all(d):
    for x in (28, 140):
        for y in (28, 140):
            d.rounded_rectangle((x, y, x + 88, y + 88), radius=16, fill=255)


@glyph("weapons")
def _weapons(d):
    # a pistol, muzzle to the right
    d.rounded_rectangle((20, 56, 236, 110), radius=10, fill=255)
    d.polygon([(40, 100), (112, 100), (100, 230), (22, 230)], fill=255)
    d.arc((92, 76, 176, 168), 0, 180, fill=255, width=16)
    d.rectangle((126, 104, 138, 140), fill=255)


@glyph("armour")
def _armour(d):
    # a helmet: dome, band and rim
    d.pieslice((24, 52, 232, 260), 180, 360, fill=255)
    d.rectangle((24, 118, 232, 132), fill=0)
    d.rounded_rectangle((8, 150, 248, 184), radius=14, fill=255)


@glyph("food")
def _food(d):
    # fork and knife
    for x in (40, 64, 88):
        d.rounded_rectangle((x, 20, x + 14, 100), radius=6, fill=255)
    d.rounded_rectangle((40, 88, 102, 124), radius=14, fill=255)
    d.rounded_rectangle((60, 116, 82, 236), radius=10, fill=255)
    d.polygon([(158, 20), (178, 20), (214, 70), (214, 140), (158, 140)], fill=255)
    d.rounded_rectangle((160, 132, 190, 236), radius=12, fill=255)


@glyph("medicine")
def _medicine(d):
    # a first-aid kit with the cross cut out
    d.rounded_rectangle((88, 30, 168, 80), radius=14, fill=255)
    d.rounded_rectangle((108, 48, 148, 80), radius=6, fill=0)
    d.rounded_rectangle((20, 70, 236, 228), radius=22, fill=255)
    d.rectangle((110, 96, 146, 204), fill=0)
    d.rectangle((74, 132, 182, 168), fill=0)


@glyph("artefacts")
def _artefacts(d):
    # a cut crystal
    d.polygon([(72, 36), (184, 36), (236, 96), (128, 232), (20, 96)], fill=255)
    for a, b in (((20, 96), (236, 96)), ((72, 36), (100, 96)), ((184, 36), (156, 96)),
                 ((100, 96), (128, 232)), ((156, 96), (128, 232))):
        d.line([a, b], fill=0, width=10)


@glyph("misc")
def _misc(d):
    # a gear: tools, devices and everything else
    for i in range(8):
        a = math.radians(i * 45 + 22.5)
        cx, cy = 128 + 92 * math.cos(a), 128 + 92 * math.sin(a)
        pts = []
        for dx, dy in ((-24, -26), (24, -26), (24, 26), (-24, 26)):
            rx = dx * math.cos(a + math.pi / 2) - dy * math.sin(a + math.pi / 2)
            ry = dx * math.sin(a + math.pi / 2) + dy * math.cos(a + math.pi / 2)
            pts.append((cx + rx, cy + ry))
        d.polygon(pts, fill=255)
    d.ellipse((46, 46, 210, 210), fill=255)
    d.ellipse((94, 94, 162, 162), fill=0)


def build():
    alpha = Image.new("L", (CELL * len(GLYPHS), CELL), 0)
    entries = []
    for i, (name, fn) in enumerate(GLYPHS.items()):
        img = Image.new("L", (W, W), 0)
        fn(ImageDraw.Draw(img))
        alpha.paste(img.resize((CELL - 8, CELL - 8), Image.LANCZOS), (i * CELL + 4, 4))
        entries.append(("ui_da_x64_inv_" + name, i * CELL + 4, 4, CELL - 8, CELL - 8))
    rgba = Image.merge("RGBA", (Image.new("L", alpha.size, 255),) * 3 + (alpha,))
    return rgba, entries


def write_descr(path, entries):
    lines = ['<?xml version="1.0" encoding="windows-1251"?>', "<w>",
             "    <!-- The actor menu's sort and filter row: generated by"
             " tools/graphics/make_inventory_tools_sheet.py, do not edit -->",
             '    <file name="ui\\ui_da_x64_inv_tools">']
    for name, x, y, w, h in entries:
        lines.append('        <texture id="%s" x="%d" y="%d" width="%d" height="%d" />' % (name, x, y, w, h))
    lines += ["    </file>", "</w>", ""]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="cp1251", newline="\r\n") as f:
        f.write("\n".join(lines))


def main():
    img, entries = build()
    write_dds(os.path.join(OUT_ROOT, "textures", "ui", "ui_da_x64_inv_tools.dds"), img)
    write_descr(os.path.join(OUT_ROOT, "configs", "ui", "textures_descr", "ui_da_x64_inv_tools.xml"), entries)
    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        bg = Image.new("RGBA", img.size, (80, 71, 63, 255))
        bg.alpha_composite(img)
        bg.resize((img.size[0] * 2, img.size[1] * 2), Image.NEAREST).save(out)
    print("%d glyphs on the sheet" % len(entries))


if __name__ == "__main__":
    main()
