# KSPR: the content key of a detail object (reference implementation, docs/dead-air/SEASON_DATA.md "KSPR")
# ---------------------------------------------------------------------------------------------------------------
FNV_OFFSET, FNV_PRIME, M64 = 0xCBF29CE484222325, 0x100000001B3, (1 << 64) - 1


def fnv1a(data, h=FNV_OFFSET):
    for b in data:
        h = ((h ^ b) * FNV_PRIME) & M64
    return h


def quant(x, k):
    v = x * k                                             # double precision
    return int(v + 0.5) if v >= 0 else -int(-v + 0.5)     # round half away from zero


def chunks(buf, off, end):
    while off + 8 <= end:
        cid, size = struct.unpack_from('<II', buf, off)
        assert not cid & 0x80000000, 'compressed chunk'
        yield cid, off + 8, size
        off += 8 + size


def detail_objects(path):
    buf = open(path, 'rb').read()
    top = {cid: (o, s) for cid, o, s in chunks(buf, 0, len(buf))}
    o, s = top[1]
    for cid, p, size in chunks(buf, o, o + s):
        e = buf.index(b'\0', p)
        shader, p = buf[p:e], e + 1
        e = buf.index(b'\0', p)
        texture, p = buf[p:e], e + 1
        flags, mn, mx, nv, ni = struct.unpack_from('<IffII', buf, p)
        V = struct.unpack_from('<%df' % (nv * 5), buf, p + 20)
        I = struct.unpack_from('<%dH' % ni, buf, p + 20 + nv * 20)
        yield cid, shader, texture, flags, mn, mx, nv, ni, V, I


def ascii_lower(b):
    return bytes(c + 32 if 65 <= c <= 90 else c for c in b)


def k1(shader, texture, flags, mn, mx, nv, ni, V, I):
    s = bytearray(ascii_lower(shader) + b'\0' + ascii_lower(texture) + b'\0')
    s += struct.pack('<Iii', flags, quant(mn, 1000), quant(mx, 1000))
    s += struct.pack('<II', nv, ni)
    for i in range(nv):
        x, y, z, u, v = V[i * 5:i * 5 + 5]
        s += struct.pack('<5i', quant(x, 1000), quant(y, 1000), quant(z, 1000), quant(u, 16384), quant(v, 16384))
    s += struct.pack('<%dH' % ni, *I)
    return fnv1a(bytes(s))


def kspr(h, V, atlas):
    buf = atlas
    H, W = struct.unpack_from('<II', buf, 12)
    off = 128 + (20 if buf[84:88] == b'DX10' else 0)
    bs = 8 if buf[84:88] == b'DXT1' else 16
    bw = (W + 3) // 4
    us, vs = V[3::5], V[4::5]
    x0, x1 = max(0, int(min(us) * W)), min(W - 1, int(max(us) * W - 1e-6))
    y0, y1 = max(0, int(min(vs) * H)), min(H - 1, int(max(vs) * H - 1e-6))
    for by in range(y0 // 4, y1 // 4 + 1):
        row = off + (by * bw + x0 // 4) * bs
        h = fnv1a(buf[row:row + (x1 // 4 - x0 // 4 + 1) * bs], h)
    return h


def verify_levels(levels_dir, hm):
    found = {}
    n_obj = 0
    for lvl in sorted(os.listdir(levels_dir)):
        det = os.path.join(levels_dir, lvl, 'level.details')
        if not os.path.isfile(det):
            continue
        atlas = open(os.path.join(levels_dir, lvl, 'build_details.dds'), 'rb').read()
        for cid, shader, texture, flags, mn, mx, nv, ni, V, I in detail_objects(det):
            key = '%016x' % kspr(k1(shader, texture, flags, mn, mx, nv, ni, V, I), V, atlas)
            found.setdefault(key, []).append('%s:%d' % (lvl, cid))
            n_obj += 1
    expected = {k: sorted(e['members']) for k, e in hm['map'].items()}
    got = {k: sorted(v) for k, v in found.items()}
    ok = got == expected
    return ok, n_obj, len(got), sorted(set(got) ^ set(expected))[:8]


