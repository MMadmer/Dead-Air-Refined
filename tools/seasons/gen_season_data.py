def num(x, places=4):
    s = ('%.*f' % (places, x)).rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s


def keylist(pairs, places=4):
    days = sorted(d for d, _ in pairs)
    for a, b in zip(days, days[1:]):
        assert b - a > 1e-3, ('duplicate key day', a, b)
    return ', '.join('%s:%s' % (num(d, 2), v if isinstance(v, str) else num(v, places)) for d, v in sorted(pairs))


def months(values):
    return list(zip(MONTH_KEYS, values))


def s2l(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def l2s(c):
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def hex_lin(h):
    assert len(h) == 7 and h[0] == '#', h
    return [s2l(int(h[i:i + 2], 16) / 255.0) for i in (1, 3, 5)]


def lin_hex(lin):
    return '#%02X%02X%02X' % tuple(int(round(255 * l2s(max(0.0, min(1.0, x))))) for x in lin)


def date_of(D):
    D = D % 365.0
    m = max(i for i in range(12) if MONTH_FIRST[i] <= D + 1e-9)
    d = D - MONTH_FIRST[m]
    hours = int(round((d - math.floor(d)) * 24))
    day = int(math.floor(d)) + 1
    if hours == 24:
        day, hours = day + 1, 0
    return '%d %s %02d:00' % (day, MONTH_NAMES[m], hours)


