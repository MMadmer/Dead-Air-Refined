def runs(flags):
    """Cyclic runs of True in a sample list: [(start index, end index)]."""
    n = len(flags)
    if all(flags):
        return [(0, n - 1)]
    out = []
    start = next(i for i in range(n) if not flags[i]) + 1
    i = 0
    while i < n:
        j = (start + i) % n
        if flags[j]:
            k = i
            while k + 1 < n and flags[(start + k + 1) % n]:
                k += 1
            out.append((j, (start + k) % n))
            i = k + 1
        else:
            i += 1
    return out


