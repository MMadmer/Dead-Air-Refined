# float32 port of DaSeasonCurve (src/xrEngine/da_season.h): every operation rounds to float like the C++ code
# ---------------------------------------------------------------------------------------------------------------
def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def wrap32(day):
    day = f32(day)
    return f32(day - f32(f32(365.0) * f32(math.floor(f32(day / 365.0)))))


class Curve:
    max_keys = 32

    def __init__(self, keys):
        assert 0 < len(keys) <= self.max_keys, ('key count', len(keys))
        pairs = sorted((wrap32(d), f32(v)) for d, v in keys)
        self.day = [d for d, _ in pairs]
        self.v = [v for _, v in pairs]
        self.n = len(pairs)
        self.m = [0.0] * self.n
        for k in range(self.n):
            p, q = (k + self.n - 1) % self.n, (k + 1) % self.n
            hp, hk = self.span(p), self.span(k)
            dp = f32(f32(self.v[k] - self.v[p]) / hp)
            dk = f32(f32(self.v[q] - self.v[k]) / hk)
            if self.n < 3 or f32(dp * dk) <= 0.0:
                self.m[k] = 0.0
            else:
                num = f32(f32(3.0) * f32(hp + hk))
                den = f32(f32(f32(f32(2.0 * hk) + hp) / dp) + f32(f32(hk + f32(2.0 * hp)) / dk))
                self.m[k] = f32(num / den)

    def span(self, k):
        h = wrap32(f32(self.day[(k + 1) % self.n] - self.day[k])) if self.n > 1 else 365.0
        return h if h > 1e-4 else 365.0

    def segment(self, x):
        k = self.n - 1
        for i in range(self.n):
            if self.day[i] <= x:
                k = i
        return k, (k + 1) % self.n

    def at(self, D):
        if self.n == 1:
            return self.v[0]
        x = wrap32(D)
        k, q = self.segment(x)
        h = self.span(k)
        s = min(max(f32(wrap32(f32(x - self.day[k])) / h), 0.0), 1.0)
        s2 = f32(s * s)
        s3 = f32(s2 * s)
        h00 = f32(f32(f32(2.0 * s3) - f32(3.0 * s2)) + 1.0)
        h10 = f32(f32(s3 - f32(2.0 * s2)) + s)
        h01 = f32(f32(-2.0 * s3) + f32(3.0 * s2))
        h11 = f32(s3 - s2)
        a = f32(h00 * self.v[k])
        b = f32(f32(h10 * h) * self.m[k])
        c = f32(h01 * self.v[q])
        d = f32(f32(h11 * h) * self.m[q])
        return f32(f32(f32(a + b) + c) + d)

    def bounds(self, D):
        """Value range of the segment D lies in (no-overshoot test)."""
        k, q = self.segment(wrap32(D))
        return min(self.v[k], self.v[q]), max(self.v[k], self.v[q])


def curve64(keys, D):
    """The same periodic monotone cubic in double precision (deriving extra key values)."""
    pairs = sorted((d % 365.0, v) for d, v in keys)
    n = len(pairs)
    day = [d for d, _ in pairs]
    v = [x for _, x in pairs]
    span = lambda k: ((day[(k + 1) % n] - day[k]) % 365.0) or 365.0
    m = []
    for k in range(n):
        p, q = (k - 1) % n, (k + 1) % n
        hp, hk = span(p), span(k)
        dp, dk = (v[k] - v[p]) / hp, (v[q] - v[k]) / hk
        m.append(0.0 if dp * dk <= 0 else 3 * (hp + hk) / ((2 * hk + hp) / dp + (hk + 2 * hp) / dk))
    x = D % 365.0
    k = n - 1
    for i in range(n):
        if day[i] <= x:
            k = i
    q = (k + 1) % n
    h = span(k)
    s = ((x - day[k]) % 365.0) / h
    return ((2 * s ** 3 - 3 * s ** 2 + 1) * v[k] + (s ** 3 - 2 * s ** 2 + s) * h * m[k] +
            (-2 * s ** 3 + 3 * s ** 2) * v[q] + (s ** 3 - s ** 2) * h * m[q])


