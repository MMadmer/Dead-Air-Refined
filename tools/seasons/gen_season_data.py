def parse_ini(text):
    sections = OrderedDict()
    cur = None
    for raw in text.split('\n'):
        line = raw.strip()
        cut = [i for i in (line.find(';'), line.find('//')) if i >= 0]
        if cut:
            line = line[:min(cut)].strip()
        if not line:
            continue
        if line.startswith('['):
            cur = line[1:line.index(']')].lower()
            assert cur not in sections, ('duplicate section', cur)
            sections[cur] = OrderedDict()
        else:
            k, v = line.split('=', 1)
            k = k.strip()
            assert k not in sections[cur], ('duplicate line', cur, k)
            sections[cur][k] = ''.join(v.split())     # _parse drops every blank outside quotes
    return sections


def parse_keys(value):
    out = []
    for item in value.split(','):
        d, v = item.split(':', 1)
        out.append((float(d), v))
    return out


def curves_of(ini):
    """Every key list of the file: (section, field) -> (Curve or [r, g, b] Curves, is_colour)."""
    out = OrderedDict()
    for sec, lines in ini.items():
        if sec in ('season_folders', 'season_categories', 'detail_types', 'grass_class_community', 'season') or \
                sec.startswith('grass_species_') or sec.startswith('grass_community_'):
            continue
        for k, v in lines.items():
            if ':' not in v or k in ('head_mix', 'seed_ramp'):
                continue
            pairs = parse_keys(v)
            if pairs[0][1].startswith('#'):
                lin = [(d, hex_lin(c)) for d, c in pairs]
                out[(sec, k)] = ([Curve([(d, c[ch]) for d, c in lin]) for ch in range(3)], True)
            else:
                out[(sec, k)] = (Curve([(d, float(x)) for d, x in pairs]), False)
    return out


def samples():
    n = int(round(365 / STEP))
    return [i * STEP for i in range(n)]


def window_days(a, b):
    """Samples of the cyclic window [a, b]."""
    return [d for d in samples() if (a <= d or d <= b)] if a > b else [d for d in samples() if a <= d <= b]


def grass_visible(cover_open, D):
    c = cover_open.at(D)
    return min(max(f32(f32(f32(0.9) - c) / f32(0.6)), 0.0), 1.0)


def check(ini):
    curves = curves_of(ini)
    errors = []
    unbounded = {('precip_keys', 't_mean'), ('precip_keys', 't_min'), ('precip_keys', 't_max'),
                 ('precip_keys', 't_range'), ('precip_keys', 't_sigma'), ('snow_keys', 'rho_open'), ('snow_keys', 'rho_road')}
    days = samples()
    stats = dict(curves=0, samples=0)
    for (sec, k), (c, colour) in curves.items():
        stats['curves'] += 1
        for ch_curve in (c if colour else [c]):
            for D in days + ch_curve.day:
                stats['samples'] += 1
                v = ch_curve.at(D)
                lo, hi = ch_curve.bounds(D)
                tol = 1e-6 * max(1.0, abs(lo), abs(hi))
                if not math.isfinite(v) or v < lo - tol or v > hi + tol:
                    errors.append('%s.%s overshoots at %.2f: %g not in [%g, %g]' % (sec, k, D, v, lo, hi))
                    break
                if (sec, k) not in unbounded and (v < 0.0 or (colour and v > 1.0)):
                    errors.append('%s.%s out of range at %.2f: %g' % (sec, k, D, v))
                    break
    # Shares 0..1 (everything but temperatures, densities, depths)
    for (sec, k), (c, colour) in curves.items():
        if colour or (sec, k) in unbounded or k.startswith('depth') or k == 'snow_depth_on_ice':
            continue
        if max(c.v) > 1.0 + 1e-6 and not (sec.startswith('grass_keys') and k == 'density'):
            errors.append('%s.%s has a key above 1' % (sec, k))
    cap = float(ini['snow_keys']['cap'])
    for short, _ in SNOW_CLASSES:
        c = curves[('snow_keys', 'depth_' + short)][0]
        if max(c.at(D) for D in days) > cap + 1e-6:
            errors.append('depth_%s above the cap' % short)

    def exact(sec, k, a, b, value, what):
        c = curves[(sec, k)][0]
        bad = [D for D in window_days(a, b) + [a, b] if c.at(D) != value]
        if bad:
            errors.append('%s: %s.%s != %g on %d samples, first %.2f (%g)' % (what, sec, k, value, len(bad), bad[0], c.at(bad[0])))
        return not bad

    def atleast(sec, k, a, b, value, what):
        c = curves[(sec, k)][0]
        low = min(c.at(D) for D in window_days(a, b) + [a, b])
        if low < value:
            errors.append('%s: %s.%s min %.6f < %g' % (what, sec, k, low, value))
        return low

    results = OrderedDict()
    # D1: zero-grass window, open cover >= 0.9 all through it, nothing herbaceous, no legacy grass
    cov = curves[('snow_keys', 'cover_open')][0]
    win = window_days(DEC_1, FEB_28) + [DEC_1, FEB_28]
    gv_max = max(grass_visible(cov, D) for D in win)
    if gv_max != 0.0:
        errors.append('D1: grass_visible %g inside the zero-grass window' % gv_max)
    results['D1 grass_visible over 1 Dec 00:00 .. 28 Feb 12:00'] = 'max %g' % gv_max
    results['D1 open cover over the window'] = 'min %.4f' % atleast('snow_keys', 'cover_open', DEC_1, FEB_28, f32(GV_COVER), 'D1')
    before, after = grass_visible(cov, DEC_1 - STEP), grass_visible(cov, FEB_28 + STEP)
    if before <= 0.0 or after <= 0.0:
        errors.append('D1: the zero-grass window is wider than 1 Dec .. 28 Feb noon')
    results['D1 grass_visible 6 h outside the window (30 Nov 18:00 / 28 Feb 18:00)'] = '%.4f / %.4f' % (before, after)
    for c in STOCK_WINDOW_ZERO:
        exact('stock_keys_' + c.lower(), 'keep', DEC_1, FEB_28, 0.0, 'D1')
    results['D1 keep of forb/herb/fern/horsetail/legacy over the window'] = 'exactly 0'
    # D2: no snow in October (nor anywhere from mid-May to 1 Nov)
    for short, _ in SNOW_CLASSES:
        exact('snow_keys', 'cover_' + short, 134.5, NOV_1, 0.0, 'D2')
        exact('snow_keys', 'depth_' + short, 134.5, NOV_1, 0.0, 'D2')
    exact('ice_keys', 'snow_cover_on_ice', 134.5, NOV_1, 0.0, 'D2')
    exact('ice_keys', 'snow_depth_on_ice', 134.5, NOV_1, 0.0, 'D2')
    results['D2 snow cover and depth over 15 May .. 1 Nov 00:00 (every class, on ice too)'] = 'exactly 0'
    # D5: roads fully covered Dec-Feb (float32 flat run of ones)
    results['D5 road cover over the window'] = 'min %.7f' % atleast('snow_keys', 'cover_road', DEC_1, FEB_28, 0.999, 'D5')
    # D6: snow only inside the window
    for k, v in (('snow', None), ('mixed', 0.0), ('rain', 0.0), ('glaze', 0.0), ('snowfall_share', None)):
        if v is None:
            atleast('precip_keys', k, DEC_1, FEB_28, 0.999999, 'D6')
        else:
            exact('precip_keys', k, DEC_1, FEB_28, v, 'D6')
    results['D6 precipitation over the window'] = 'snow and snowfall_share 1, mixed / rain / glaze exactly 0'
    # D3: cap and drift-only cap
    dmax = {s: max(curves[('snow_keys', 'depth_' + s)][0].at(D) for D in days) for s, _ in SNOW_CLASSES}
    results['D3 max depth open / trees / road / drift (m)'] = ' / '.join('%.3f' % dmax[s] for s, _ in SNOW_CLASSES)
    if max(dmax['open'], dmax['trees'], dmax['road']) >= cap - 0.1:
        errors.append('D3: only drift cores may approach the cap')
    # Texture folders: winter overlays only under full open cover
    for cat, table in FOLDERS.items():
        wd = [D for D in days if folder_at(cat, int(math.floor(D))) == 'winter']
        if cat in ('trees', 'decal') and wd:
            low = min(cov.at(D) for D in wd)
            results['folders: %s winter days, min open cover' % cat] = '%d days, %.4f' % (len(wd) * STEP, low)
            if low < 0.99:
                errors.append('folders: %s wears winter with open cover %.3f' % (cat, low))
        if cat in ('default', 'ground') and wd:
            errors.append('folders: %s must never be winter' % cat)
    results['curves checked / samples'] = '%d / %d' % (stats['curves'], stats['samples'])
    return errors, results, curves


