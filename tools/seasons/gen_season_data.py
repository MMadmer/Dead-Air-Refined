class Ltx:
    def __init__(self):
        self.sections = OrderedDict()
        self.notes = {}

    def section(self, name, note=None):
        assert name == name.lower(), ('CInifile stores section names in lower case', name)
        assert name not in self.sections, name
        self.sections[name] = []
        if note:
            self.notes[name] = note
        return self.sections[name]

    def text(self, header):
        out = list(header)
        for name, lines in self.sections.items():
            out.append('')
            for c in self.notes.get(name, []):
                out.append('; ' + c if c else ';')
            out.append('[%s]' % name)
            width = max((len(k) for k, _ in lines), default=0)
            for k, v in lines:
                assert len(k) + len(v) < 4000, ('CInifile line limit', name, k)
                out.append('%-*s = %s' % (width, k, v))
        text = '\r\n'.join(out) + '\r\n'
        text.encode('ascii')
        return text


def snow_sections(ltx, kf, precip):
    """[snow_keys], [precip_keys], [ice_keys]; returns the still-water ice keys (the floodplain profiles freeze with them)."""
    mon = kf['months']
    snow = OrderedDict()
    # Cover and depth per class: the 12 keyframes plus the D2 (1 Nov) and D1 (1 Dec, 28 Feb noon) keys
    open_cover = [m['snow']['coverage']['open'] for m in mon]
    for short, long_ in SNOW_CLASSES:
        cover = [m['snow']['coverage'][long_] for m in mon]
        depth = [min(m['snow']['depth_m'][long_], CAP) for m in mon]
        base_depth = months(depth)
        # D1: open cover reaches GV_COVER on 1 Dec and leaves it on 28 Feb noon; the other classes move by the same
        # share of their Nov->Dec and Feb->Mar steps, roads stay fully covered (D5)
        a = (GV_COVER - open_cover[10]) / (open_cover[11] - open_cover[10])
        b = (open_cover[1] - GV_COVER) / (open_cover[1] - open_cover[2])
        on = 1.0 if short == 'road' else round(cover[10] + a * (cover[11] - cover[10]), 3)
        off = 1.0 if short == 'road' else round(cover[1] + b * (cover[2] - cover[1]), 3)
        snow['cover_' + short] = months(cover) + [(NOV_1, 0.0), (DEC_1, on), (FEB_28, off)]
        snow['depth_' + short] = months(depth) + [
            (NOV_1, 0.0), (DEC_1, round(min(curve64(base_depth, DEC_1), CAP), 3)),
            (FEB_28, round(min(curve64(base_depth, FEB_28), CAP), 3))]
    for w in ('fresh', 'settled', 'old', 'wet'):
        snow['state_' + w] = months([m['snow']['state_weights'][w] for m in mon])
    snow['age'] = months([m['snow']['age'] for m in mon])
    snow['crust'] = months([m['snow']['crust'] for m in mon])
    snow['wet'] = months([m['snow']['wetness'] for m in mon])
    snow['drift'] = months([m['snow']['drift_strength'] for m in mon])
    snow['comp_road'] = months([m['snow']['compaction_roads'] for m in mon])
    snow['rho_open'] = months([m['snow']['density_kg_m3']['open'] for m in mon])
    snow['rho_road'] = months([m['snow']['density_kg_m3']['roads'] for m in mon])
    snow['dirt_road'] = months([m['snow']['dirt_roadside'] for m in mon])
    snow['litter_trees'] = months([m['snow']['litter_under_trees'] for m in mon])
    snow['albedo_open'] = months([m['snow']['colour']['open'] for m in mon])
    snow['albedo_road'] = months([m['snow']['colour']['roads'] for m in mon])
    snow['albedo_trees'] = months([m['snow']['colour']['under_trees'] for m in mon])
    for m in mon:
        assert abs(m['snow']['depth_cap_m'] - CAP) < 1e-9
    s = ltx.section('snow_keys', [
        'Snow of the season per surface class: open ground, under tree canopy, roads, drifts and neglected spots.',
        'cover_* = covered share of the class, depth_* = game metres where it lies (mean of the covered part; drift =',
        'P90 of the covered drift cells), cap applied. The other lists describe the state of the snow. Extra keys:',
        '304 (1 Nov 00:00) no snow yet; open cover is exactly 0.9 at 334 (1 Dec 00:00) and 58.5 (28 Feb noon) and',
        'above it in between, so grass_visible = saturate((0.9 - cover_open) / 0.6) is 0 exactly over that window.'])
    s.append(('cap', num(CAP)))
    for k, pairs in snow.items():
        s.append((k, keylist(pairs, 3)))

    # Precipitation phase (D6: inside the zero-grass window everything falls as snow)
    pm = precip['months']
    window = (11, 0, 1)
    pk = OrderedDict()
    def phase(name, values, inside):
        if inside is None:
            pk[name] = months(values)
        else:
            vals = [inside if i in window else v for i, v in enumerate(values)]
            pk[name] = months(vals) + [(DEC_1, inside), (FEB_28, inside)]
    phase('snow', [m['phase']['snow'] for m in pm], 1.0)
    phase('mixed', [m['phase']['mixed'] for m in pm], 0.0)
    phase('rain', [m['phase']['rain'] for m in pm], 0.0)
    phase('snowfall_share', [m['snowfall_share'] for m in pm], 1.0)
    phase('p_precip', [m['p_precip_day'] for m in pm], None)
    phase('thunder_weight', [m['thunder_weight'] for m in pm], None)
    phase('glaze', [m['p_freezing_rain_given_precip_day'] for m in pm], 0.0)
    phase('frost_night', [m['p_frost_night'] for m in pm], None)
    phase('t_mean', [m['T_mean_C'] for m in pm], None)
    phase('t_min', [m['T_min_C'] for m in pm], None)
    phase('t_max', [m['T_max_C'] for m in pm], None)
    phase('t_range', [round(m['T_max_C'] - m['T_min_C'], 2) for m in pm], None)
    phase('t_sigma', [m['daily_T_sigma_C'] for m in pm], None)
    fit = precip['meta']['fit']
    s = ltx.section('precip_keys', [
        'Precipitation phase by day: the weather decides how much falls, the season what falls. Shares of',
        'precipitation days (snow + mixed + rain = 1 at the keys), temperatures in C, the logistic phase model and',
        'the snow-only window (334 .. 58.5: 1 Dec 00:00 .. 28 Feb noon, the zero-grass window).'])
    for k, pairs in pk.items():
        s.append((k, keylist(pairs, 3)))
    # Annual mean temperature fit T(doy) = 7.89 + 12.14 cos(2 pi (doy - 195) / 365), doy 1-based: day D = doy - 0.5
    s += [('t_mean_a', '7.89'), ('t_mean_b', '12.14'), ('t_mean_phase', '194.5'),
          ('ts', num(fit['Ts_C'])), ('tl', num(fit['Tl_C'])), ('w', num(fit['w_C'])),
          ('t_precip_bias', num(fit['dT_precip_day_warm_bias_C'])), ('t_precip_sigma', num(fit['sigma_scale_precip_days'])),
          ('snow_only', '%s, %s' % (num(DEC_1), num(FEB_28)))]

    # Water ice; snow on ice follows the open cover and depth (open cover x max ice, 0.8 x open depth)
    still = months([m['ice']['still'] for m in pm])
    flowing = months([m['ice']['flowing'] for m in pm])
    cover_on = months([m['ice']['snow_on_ice_cover'] for m in pm])
    depth_on = months([m['ice']['snow_on_ice_depth_m'] for m in pm])
    for D in (NOV_1, DEC_1, FEB_28):
        ice = max(curve64(still, D), curve64(flowing, D))
        cover_on.append((D, round(curve64(snow['cover_open'], D) * ice, 3)))
        depth_on.append((D, round(0.8 * curve64(snow['depth_open'], D), 3)))
    s = ltx.section('ice_keys', [
        'Ice on still water (ponds, oxbows, marsh pools, floodplain) and flowing water (channels, streams); snow lying',
        'on the ice (cover = open cover x ice, depth = 0.8 x open depth, metres). Visual only (D7).'])
    s.append(('still', keylist(still, 3)))
    s.append(('flowing', keylist(flowing, 3)))
    s.append(('snow_cover_on_ice', keylist(cover_on, 3)))
    s.append(('snow_depth_on_ice', keylist(depth_on, 3)))
    return still


def shifted(values, shift):
    """A template's 12 month values read `shift` days later over the growing season (1 Mar - 31 Oct), the dormant
    months as the template has them: an early species reaches the template's state of D at D + shift."""
    keys = months(values)
    out = []
    for D, v in zip(MONTH_KEYS, values):
        out.append(round(max(curve64(keys, D - shift), 0.0), 4) if 59 <= D <= 304 else v)
    return out


def smooth(a, b, x):
    if b <= a:
        return 1.0 if x >= b else 0.0
    t = min(max((x - a) / (b - a), 0.0), 1.0)
    return t * t * (3 - 2 * t)


def forb_keys(s, mon):
    """Season keys of a forb from its phenology (make_species.py phen): semi-monthly keys of its growth, green,
    thatch, heads and stage, the climate keys (wetness, frost, density, flood) of its climate template."""
    ph = s['phen']
    clim = [m['grass'][ph['climate']] for m in mon]
    wg = ph['winter_green']
    base = 0.3 if wg > 0 else 0.0
    keys = OrderedDict()
    for k in ('new_growth_h', 'green', 'cohort_green', 'thatch', 'thatch_lodge', 'straw_lodge', 'heads', 'seed_stage',
              'tip_dry'):
        keys[k] = []
    for D in HALF_MONTH_KEYS:
        dormant = D < ph['up'] - 30                  # until a month before emergence: last year's stems only
        grow = base + (1 - base) * smooth(ph['up'], ph['full'], D)
        green = 0.0 if D < ph['up'] else min((D - ph['up']) / 30.0, 1.0)
        green = max(green * (1 - smooth(ph['sen0'], ph['sen1'], D)), wg)
        cohort = 1.0 - smooth(ph['sen0'], ph['sen1'], D)
        cohort = max(cohort, wg) if D >= ph['sen0'] else 1.0
        # Last year's stems: standing in early spring, falling and decaying by midsummer.
        stand = ph['stand'] * (1 - smooth(90, 200, D)) if D < 334 else ph['stand']
        heads = smooth(ph['bud'] - 15, ph['flower'], D) * (1 - 0.2 * smooth(ph['end'], ph['end'] + 40, D))
        if D < ph['bud']:
            stage = 0.0
        elif D < ph['flower']:
            stage = 0.25 + 0.25 * (D - ph['bud']) / max(ph['flower'] - ph['bud'], 1)
        elif D < ph['ripe']:
            stage = 0.5 + 0.25 * (D - ph['flower']) / max(ph['ripe'] - ph['flower'], 1)
        elif D < ph['end']:
            stage = 0.75 + 0.25 * (D - ph['ripe']) / max(ph['end'] - ph['ripe'], 1)
        else:
            stage = 1.0
        if D >= 334:
            # December: the dead stems of the year, the heads they keep into spring (the engine's old heads).
            stage = 1.0
        elif dormant:
            grow, green, cohort, heads, stage = base, wg, max(wg, 0.0), 0.0, 0.0
        keys['new_growth_h'].append((D, round(grow, 4)))
        keys['green'].append((D, round(green, 4)))
        keys['cohort_green'].append((D, round(cohort, 4)))
        keys['thatch'].append((D, round(stand, 4)))
        keys['thatch_lodge'].append((D, round(min(ph['lodge'] + 0.25 * smooth(90, 200, D), 1.0), 4)))
        keys['straw_lodge'].append((D, round(0.02 + 0.2 * smooth(ph['sen1'], ph['sen1'] + 45, D), 4)))
        keys['heads'].append((D, round(heads, 4)))
        keys['seed_stage'].append((D, round(stage, 4)))
        keys['tip_dry'].append((D, round(0.03 + 0.3 * smooth(ph['sen0'], ph['sen1'], D), 4)))
