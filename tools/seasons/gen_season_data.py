def write_crlf(path, text):
    with open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)


def doc_block(summary_lines, results, errors, info, kspr_line):
    out = [DOC_BEGIN, '', '### Checks', '']
    out.append('- %d detail content keys (KSPR), %d of them the Stancia FIX_EMPTY sprites written as PG_BUNCH; per class: %s.' % (
        sum(info['counts'].values()), info['fix_empty'],
        ', '.join('%s %d' % (k, info['counts'][k]) for k in CLASS_ORDER)))
    if kspr_line:
        out.append('- ' + kspr_line)
    for k, v in results.items():
        out.append('- %s: %s.' % (k, v))
    out.append('- Overshoot, negative and range errors: %s.' % ('none' if not errors else '; '.join(errors)))
    out += ['', '### Month summary', ''] + summary_lines + [DOC_END]
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='compare the tree with a fresh run, write nothing')
    ap.add_argument('--levels', help='folder with <level>/level.details and build_details.dds: recompute every KSPR')
    a = ap.parse_args()

    text, info = build()
    ini = parse_ini(text)
    errors, results, curves = check(ini)
    lines = summary(ini, curves)
    kspr_line = None
    if a.levels:
        ok, n_obj, n_keys, diff = verify_levels(a.levels, load('detail_hash_map.json'))
        kspr_line = 'KSPR recomputed from %d objects of the shipped levels: %d keys, %s.' % (
            n_obj, n_keys, 'identical to [detail_types]' if ok else 'DIFFERENT: %s' % diff)
        if not ok:
            errors.append(kspr_line)
    print('\n'.join(lines))
    for k, v in results.items():
        print('%s: %s' % (k, v))
    if kspr_line:
        print(kspr_line)
    for e in errors:
        print('ERROR: ' + e)
    if errors:
        return 1

    with open(DOC, encoding='utf-8', newline='') as f:
        doc = f.read()
    b, e = doc.find(DOC_BEGIN), doc.find(DOC_END)
    assert b >= 0 and e > b, 'generated block markers missing in ' + DOC
    if not kspr_line:
        # Keep the last recorded level verification when the shipped levels are not at hand
        old = doc[b:e]
        prev = [l[2:] for l in old.split('\r\n') if l.startswith('- KSPR recomputed')]
        kspr_line = prev[0] if prev else None
    block = '\r\n'.join(doc_block(lines, results, errors, info, kspr_line))
    new_doc = doc[:b] + block + doc[e + len(DOC_END):]
    if a.check:
        same = open(LTX, encoding='ascii', newline='').read() == text and doc == new_doc
        print('tree is %s' % ('up to date' if same else 'OUT OF DATE: run tools/seasons/gen_season_data.py'))
        return 0 if same else 1
    write_crlf(LTX, text)
    write_crlf(DOC, new_doc)
    print('wrote %s (%d sections), %s' % (os.path.relpath(LTX, ROOT), len(ini), os.path.relpath(DOC, ROOT)))
    return 0


