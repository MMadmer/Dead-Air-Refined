"""The climate's own weather cycles (docs/dead-air/WEATHER.md).

The climate (src/xrEngine/da_climate.cpp) picks the sky hour by hour. Dead Air's AtmosFear cycles tell a day's story
- the rain cycle clears to sunshine at noon, the cloudy one sinks into a 200 m fog at noon, the clear one dims for
two hours in the afternoon - so a sky the climate holds for six hours would change under it. These cycles hold one
sky through the day, built from Dead Air's own keys:

  clear_steady  af3_day_clear with its afternoon dimming (14:00-16:00) bridged from 13:00 to 17:00
  rain_steady   af3_day_storm lightened: a steady frontal rain, not a squall (fog 2.5x farther, sky light 1.2x,
                rain ambients, no lightning)
  snow          af3_day_cloudy_no_sun: a grey snow sky, the air luminous with flakes (fog lifted towards grey,
                a cooler sky light), quiet fog ambients
  blizzard      af3_day_storm: the gale's darkness and wind ambients, the fog white with blowing snow, closer

Each comes as af3_day_<state>.ltx (the day keys) and af3_<night>_<state>[_<moon>].ltx for the four night
brightnesses AtmosFear offers (slight, bright, medium, dark), whose night keys come from the stock file of the same
brightness (and moon phase). How much falls, its phase and the wind are the climate's whatever a cycle says, and
the plants sway by the wind alone: the stock tree keys are left out.

    python tools/seasons/gen_weather_cycles.py --src <dir> [--src <dir> ...] [--out <dir>]

--src: folders with Dead Air's stock cycles (configs.xdb0 and xtra.xdb0 unpacked: configs/environment/weathers);
the later one wins. --out defaults to the compatibility overlay.
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'packaging', 'dead-air-x64', 'compatibility', 'gamedata', 'configs', 'environment',
                   'weathers')
NIGHTS = ['slight', 'bright', 'medium', 'dark']
MOONS = range(8)

HEADER = ('; Generated by tools/seasons/gen_weather_cycles.py from Dead Air\'s own cycles (docs/dead-air/WEATHER.md).\n'
          '; Do not edit by hand.\n')


def parse(path):
    """[(time or None for an include line, [(key, value)], raw include)] in file order."""
    items = []
    cur = None
    with open(path, encoding='cp1251', errors='replace') as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith(';'):
                continue
            if s.startswith('#include'):
                cur = None
                items.append((None, None, s))
                continue
            m = re.match(r'^\[([0-9:]+)\]', s)
            if m:
                cur = (m.group(1), [])
                items.append((cur[0], cur[1], None))
                continue
            if cur is not None and '=' in s:
                k, v = s.split('=', 1)
                cur[1].append((k.strip(), v.strip()))
    return items


def write(path, items, include=None):
    with open(path, 'w', encoding='cp1251', newline='\n') as f:
        f.write(HEADER)
        for t, kv, inc in items:
            if t is None:
                f.write('\n#include("%s")\n' % include if include else '\n%s\n' % inc)
                continue
            f.write('\n[%s]\n' % t)
            for k, v in kv:
                f.write('        %-32s = %s\n' % (k, v))


def floats(v):
    try:
        return [float(x) for x in v.split(',')]
    except ValueError:
        return None


def fmt(vals):
    return ', '.join('%.6f' % x for x in vals)


def get(kv, key):
    for k, v in kv:
        if k == key:
            return v
    return None


def put(kv, key, value):
    for i, (k, v) in enumerate(kv):
        if k == key:
            kv[i] = (k, value)
            return
    kv.append((key, value))


def drop(kv, key):
    kv[:] = [(k, v) for k, v in kv if k != key]


def scale(kv, key, mul, add=0.0, lo=0.0, hi=1.0, keep_w=True):
    v = get(kv, key)
    if v is None:
        return
    f = floats(v)
    if f is None:
        return
    n = 3 if (keep_w and len(f) == 4) else len(f)
    out = [min(max(f[i] * (mul[i] if isinstance(mul, (list, tuple)) else mul) + add, lo), hi) for i in range(n)]
    put(kv, key, fmt(out + f[n:]))


def luminance(c):
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]


def secs(t):
    h, m, s = (int(x) for x in t.split(':'))
    return h * 3600 + m * 60 + s


def find(srcs, name):
    path = None
    for d in srcs:
        p = os.path.join(d, name)
        if os.path.exists(p):
            path = p
    if not path:
        raise SystemExit('missing source cycle: ' + name)
    return path


# ---- transforms ------------------------------------------------------------------------------------------

def clear_steady_day(items):
    keys = {t: kv for t, kv, _ in items if t}
    a, b = keys['13:00:00'], keys['17:00:00']
    ta, tb = secs('13:00:00'), secs('17:00:00')
    for t in ('14:00:00', '15:00:00', '16:00:00'):
        kv = keys.get(t)
        if kv is None:
            continue
        w = (secs(t) - ta) / float(tb - ta)
        for k, v in a:
            fa, fb = floats(v), floats(get(b, k) or '')
            if fa and fb and len(fa) == len(fb) and k not in ('sun_longitude', 'sun_altitude'):
                put(kv, k, fmt([x + (y - x) * w for x, y in zip(fa, fb)]))
        put(kv, 'ambient', 'day')
        put(kv, 'sun', get(a, 'sun'))
    return items


def rain_steady(items, night=False):
    for t, kv, _ in items:
        if not t:
            continue
        fd = floats(get(kv, 'fog_distance') or '200')[0]
        put(kv, 'fog_distance', '%.6f' % min(fd * 2.5, 900.0))
        fp = floats(get(kv, 'far_plane') or '200')[0]
        put(kv, 'far_plane', '%.6f' % max(fp, min(fd * 2.5, 900.0)))
        put(kv, 'fog_density', '0.900000')
        scale(kv, 'hemisphere_color', 1.2)
        scale(kv, 'sky_color', 1.05)
        put(kv, 'rain_density', '0.600000')
        put(kv, 'thunderbolt_collection', '')
        put(kv, 'wind_velocity', '150.000000')
        amb = get(kv, 'ambient') or ''
        put(kv, 'ambient', 'rain_night' if (night or 'night' in amb) else 'rain_day')
    return items


SNOW_TINT = (0.95, 1.0, 1.06)


def snow(items, night=False):
    for t, kv, _ in items:
        if not t:
            continue
        hemi = floats(get(kv, 'hemisphere_color') or '0.3,0.3,0.3,1')
        fog = floats(get(kv, 'fog_color') or '0.1,0.1,0.1')
        # The air full of flakes is lit grey-white: the fog goes neutral and brighter, towards the sky light's level.
        lum = max(luminance(fog) * 1.35, luminance(hemi[:3]) * (0.45 if night else 0.6))
        put(kv, 'fog_color', fmt([min(lum * c, 1.0) for c in SNOW_TINT]))
        scale(kv, 'hemisphere_color', list(SNOW_TINT))
        fd = floats(get(kv, 'fog_distance') or '800')[0]
        put(kv, 'fog_distance', '%.6f' % min(fd * 0.75, 700.0))
        put(kv, 'fog_density', '0.950000')
        put(kv, 'rain_density', '0.500000')
        put(kv, 'rain_color', '0.850000, 0.870000, 0.900000')
        put(kv, 'thunderbolt_collection', '')
        put(kv, 'wind_velocity', '120.000000')
        amb = get(kv, 'ambient') or ''
        put(kv, 'ambient', 'tuman_night' if (night or 'night' in amb) else 'tuman_day')
    return items


def blizzard(items, night=False):
    for t, kv, _ in items:
        if not t:
            continue
        hemi = floats(get(kv, 'hemisphere_color') or '0.3,0.3,0.3,1')
        # Blowing snow scatters the sky light: a white-grey wall, darker than a snowfall's.
        lum = luminance(hemi[:3]) * (0.5 if night else 0.75)
        put(kv, 'fog_color', fmt([min(lum * c, 1.0) for c in SNOW_TINT]))
        scale(kv, 'hemisphere_color', [1.1 * c for c in SNOW_TINT])
        put(kv, 'fog_distance', '150.000000')
        put(kv, 'far_plane', '%.6f' % max(floats(get(kv, 'far_plane') or '200')[0], 150.0))
        put(kv, 'fog_density', '1.000000')
        put(kv, 'rain_density', '1.000000')
        put(kv, 'rain_color', '0.850000, 0.870000, 0.900000')
        put(kv, 'thunderbolt_collection', '')
        put(kv, 'wind_velocity', '500.000000')
        amb = get(kv, 'ambient') or ''
        put(kv, 'ambient', 'storm_night' if (night or 'night' in amb) else 'storm_day')
    return items


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', action='append', required=True)
    ap.add_argument('--out', default=OUT)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    made = []

    def emit(name, items, include=None):
        # (The engine takes a plant's sway from the wind service alone.)
        for t, kv, _ in items:
            if t:
                drop(kv, 'tree_amplitude_intensity')
        write(os.path.join(a.out, name), items, include)
        made.append(name)

    emit('af3_day_clear_steady.ltx', clear_steady_day(parse(find(a.src, 'af3_day_clear.ltx'))))
    emit('af3_day_rain_steady.ltx', rain_steady(parse(find(a.src, 'af3_day_storm.ltx'))))
    emit('af3_day_snow.ltx', snow(parse(find(a.src, 'af3_day_cloudy_no_sun.ltx'))))
    emit('af3_day_blizzard.ltx', blizzard(parse(find(a.src, 'af3_day_storm.ltx'))))
    for n in NIGHTS:
        for m in MOONS:
            emit('af3_%s_clear_steady_%d.ltx' % (n, m), parse(find(a.src, 'af3_%s_clear_%d.ltx' % (n, m))),
                 'af3_day_clear_steady.ltx')
        emit('af3_%s_rain_steady.ltx' % n, rain_steady(parse(find(a.src, 'af3_%s_storm.ltx' % n)), True),
             'af3_day_rain_steady.ltx')
        emit('af3_%s_snow.ltx' % n, snow(parse(find(a.src, 'af3_%s_cloudy_no_sun.ltx' % n)), True), 'af3_day_snow.ltx')
        emit('af3_%s_blizzard.ltx' % n, blizzard(parse(find(a.src, 'af3_%s_storm.ltx' % n)), True),
             'af3_day_blizzard.ltx')
    print('%d cycle files -> %s' % (len(made), a.out))


if __name__ == '__main__':
    main()
