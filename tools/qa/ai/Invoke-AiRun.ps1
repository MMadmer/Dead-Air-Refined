# One stand run of the human NPC AI (TEST_MATRIX.md "NPC AI"). Stages every engine binary of the rig that differs
# from bin\x64\Release under ninja.lock, then under stand.lock syncs the whole compatibility overlay into the rig (the
# AI's Lua side lives there, not only its configs) and runs Run-WaterQa.ps1 with the shader cache kept. The run folder
# gets the log, the probe's lines and run.txt (command, staged binaries, their SHA-256).
#
#   tools\qa\ai\Invoke-AiRun.ps1 -Name r1-ai-fair -Scenario ai_fair -Save foliage
#   tools\qa\ai\Invoke-AiRun.ps1 -Name r4b-ai-save -Scenario ai_save -Save qa_ai_mid -Globals 'qa_ai_phase = "b"'
#   tools\qa\ai\Invoke-AiRun.ps1 -Name r6-ai-newgame -Scenario ai_newgame -NewGame
#
# -NewGame starts a new game instead of loading a save: the rig's axr_options.ltx gets the start the new-game screen
# would write (a loner at the rookie village; without one Dead Air never leaves fake_start) and is restored after the
# run. Its ceiling stays below five minutes.
#
# Verdict: python tools\qa\ai\Parse-AiLog.py <run folders> --out verdict.md
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$Name,
    [Parameter(Mandatory)][string]$Scenario,
    [string]$Save = 'foliage',
    [int]$Seconds = 150,
    [string]$Globals = '',
    [string[]]$PreCommands = @(),
    [string]$ExtraArgs = '-force_flushlog -always_active',
    [string]$Rig = 'D:\Games\Dead Air\_qa\lightdiag',
    [string]$Out = 'D:\Games\Dead Air\_work\ai-npc\qa',
    [switch]$NewGame
)

$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..\..\..')).Path
$bin = Join-Path $repo 'bin\x64\Release'
$overlay = Join-Path $repo 'packaging\dead-air-x64\compatibility\gamedata'
if (-not $env:DX12_LANE) { $env:DX12_LANE = 'ai-qa' }
. (Join-Path $repo 'tools\qa\dx12\Dx12Locks.ps1')
$PreCommands = @($PreCommands | ForEach-Object { $_ -split ';' } | ForEach-Object Trim | Where-Object { $_ })

# Every engine binary the rig already carries that differs from the build output (size or time).
$staging = Join-Path $env:TEMP ('airun-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Force -Path $staging | Out-Null
$ninja = Enter-Lock 'ninja'
try {
    Get-ChildItem -LiteralPath $bin -File | Where-Object {
        $_.Extension -in '.dll', '.exe', '.pdb' -and ($_.Name -like 'xr*' -or $_.Name -eq 'XR_3DA.pdb')
    } | ForEach-Object {
        $target = Join-Path $Rig $_.Name
        $have = Get-Item -LiteralPath $target -ErrorAction SilentlyContinue
        if ($have -and ($have.Length -ne $_.Length -or $have.LastWriteTimeUtc -ne $_.LastWriteTimeUtc)) {
            Copy-Item -LiteralPath $_.FullName -Destination $staging -Force
        }
    }
} finally { Exit-Lock $ninja }

$stand = Enter-Lock 'stand'
try {
    $rigEngines = { @(Get-CimInstance Win32_Process -Filter "Name='xrEngine.exe'" -ErrorAction SilentlyContinue |
        Where-Object { $_.ExecutablePath -like "$Rig\*" }) }
    foreach ($engine in & $rigEngines) {
        Write-Host "stopping leftover rig engine $($engine.ProcessId)"
        Stop-Process -Id $engine.ProcessId -Force -ErrorAction SilentlyContinue
        Wait-Process -Id $engine.ProcessId -Timeout 15 -ErrorAction SilentlyContinue
    }
    $copied = @(Get-ChildItem -LiteralPath $staging -File)
    foreach ($file in $copied) { Copy-Item -LiteralPath $file.FullName -Destination $Rig -Force }
    & robocopy $overlay (Join-Path $Rig 'gamedata') /E /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy of the overlay failed ($LASTEXITCODE)" }

    $started = Get-Date
    $dest = Join-Path $Out $Name
    if ($NewGame) {
        # A new game: the probe script is staged the way Run-WaterQa does it, only the start command differs.
        $lua = Join-Path $repo "tools\qa\water\$Scenario.lua"
        Set-Content -LiteralPath (Join-Path $Rig 'gamedata\scripts\qa_water.script') -Encoding UTF8 `
            -Value ("-- generated by Invoke-AiRun.ps1`n$Globals`n" + [IO.File]::ReadAllText($lua))
        # The start the new-game screen writes; Dead Air's fake_start moves the player there and clears the keys.
        $options = Join-Path $Rig 'gamedata\configs\axr_options.ltx'
        $optionsBackup = "$options.airun-backup"
        Copy-Item -LiteralPath $options -Destination $optionsBackup -Force
        try {
            $text = [IO.File]::ReadAllText($options)
            foreach ($pair in @(@('new_game_faction', 'stalker'), @('new_game_faction_position', '_rookie_village'))) {
                $pattern = '(?m)^([ \t]*' + $pair[0] + '[ \t]*=)[^\r\n]*'
                if ($text -notmatch $pattern) { throw "axr_options.ltx has no $($pair[0]) line" }
                $text = [regex]::Replace($text, $pattern, '${1} ' + $pair[1])
            }
            [IO.File]::WriteAllText($options, $text)
            $ceiling = [Math]::Min($Seconds, 280)
            & (Join-Path $repo 'tools\qa\Run-ContentProbe.ps1') -Rig $Rig -Label $Name -RunSeconds $ceiling `
                -TimeoutSeconds ($ceiling + 10) -WaitFor 'DA_WATER_PROBE_DONE' -ExtraArgs $ExtraArgs `
                -Commands ($PreCommands + @('start server(all/single/alife/new) client(localhost)')) | Out-Null
        } finally {
            Copy-Item -LiteralPath $optionsBackup -Destination $options -Force
            Remove-Item -LiteralPath $optionsBackup -Force -ErrorAction SilentlyContinue
        }
        New-Item -ItemType Directory -Force -Path $dest | Out-Null
        Copy-Item (Join-Path $Rig 'appdata\logs\grizzly_admin.log') (Join-Path $dest 'log.txt') -Force
    } else {
        & (Join-Path $repo 'tools\qa\Run-WaterQa.ps1') -Name $Name -Scenario $Scenario -Save $Save -Seconds $Seconds `
            -KeepShaderCache -ExtraArgs $ExtraArgs -PreCommands $PreCommands -Globals $Globals -Overlay $overlay `
            -Out $Out -Rig $Rig
    }
    $hashes = foreach ($n in 'xrGame.dll', 'xrEngine.dll', 'xrEngine.exe', 'xrAICore.dll', 'xrCore.dll') {
        '{0}  {1}' -f (Get-FileHash -LiteralPath (Join-Path $Rig $n) -Algorithm SHA256).Hash, $n
    }
    @("run: $Name", "started: $(Get-Date $started -Format s)",
        "seconds: $([int]((Get-Date) - $started).TotalSeconds)", "scenario: $Scenario", "save: $Save",
        "args: $ExtraArgs", "pre: $($PreCommands -join ' | ')", "globals: $($Globals -replace "`n", ' ; ')",
        "staged: $(($copied | ForEach-Object Name) -join ', ')", '') + $hashes |
        Set-Content -LiteralPath (Join-Path $dest 'run.txt') -Encoding UTF8
} finally {
    Remove-Item -LiteralPath (Join-Path $Rig 'gamedata\scripts\qa_water.script') -Force -ErrorAction SilentlyContinue
    Exit-Lock $stand
    Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue
}
