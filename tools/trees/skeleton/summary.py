"""Stage 6: out/report/fit.csv (one row per stock axis), out/report/skeletons.csv (one row per skeleton) and
out/report/README.md (totals, gate by class, patch share, worst cases)."""
import collections
import csv
import io
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import common as C  # noqa: E402
import job  # noqa: E402


def load_results():
    d = os.path.join(C.WORK, 'result')
    out = {}
    if not os.path.isdir(d):
        return out
    for f in sorted(os.listdir(d)):
        if f.endswith('.json'):
            with open(os.path.join(d, f), encoding='utf-8') as fh:
                r = json.load(fh)
            out[r['skel']] = r
    return out


def cls_of(r):
    if r.get('procedural'):
        return 'BUSH_KEPT_STOCK' if 'BUSH_KEPT_STOCK' in r.get('categories', []) else 'PROCEDURAL'
    st = r.get('states', [])
    if 'ALIVE' in st:
        return 'TREE ALIVE'
    if 'BROKEN' in st:
        return 'TREE BROKEN'
    return 'TREE DEAD'


def csv_text(header, rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator='\r\n')
    w.writerow(header)
    w.writerows(rows)
    return buf.getvalue()


def gate_word(g):
    if g.get('p99') is None:
        return 'n/a'
    return 'pass' if job.gate_ok(g) else 'FAIL'


def f2(x, k=4):
    return '' if x is None else round(float(x), k)


def main():
    plan = json.load(open(os.path.join(C.WORK, 'plan.json'), encoding='utf-8'))['skeletons']
    res = load_results()
    rows = []
    srows = []
    for sid in sorted(res):
        r = res[sid]
        if r.get('error'):
            srows.append([sid, ' '.join(r.get('kinds', [])), 'ERROR'] + [''] * 17)
            continue
        g = r.get('gate') or {}
        cl = cls_of(r)
        cr = r.get('crown') or {}
        so = r.get('second_opinion') or []
        srows.append([sid, ' '.join(r['kinds']), cl, ' '.join(r.get('species', [])), r['flags'], r['axes'],
                      r['axes_level0'], r['axes_level1'], r['axes_level2'], r['rings'], r['patch_tris'],
                      r['cards'], r['bytes'], f2(r.get('patch_area_share')), f2(r.get('fit_err_p99')),
                      f2(g.get('p99')), f2(g.get('world_p99')), f2(g.get('reverse_p99')), f2(g.get('climb_share'), 3),
                      '' if g.get('climb_tol') is None else g['climb_tol'],
                      gate_word(g), f2(r.get('crown_cell'), 3), cr.get('hulls_used', ''),
                      f2(cr.get('clipped_area_share'), 3),
                      ' '.join(f'{v["piece"]}:{v["chosen"]}' for v in so)])
        for a in r.get('axis_rows', []):
            rows.append([sid, cl, a['axis'], a['level'], a['parent'], a['rings'], a['stock_rings'],
                         f2(a['length'], 3), f2(a['r_base']), f2(a['max_err']), f2(a['p99_err']),
                         f2(a.get('p99_cform')), f2(a['climbable'], 3), a['flags']])
    os.makedirs(C.OUT_REPORT, exist_ok=True)
    C.atomic_text(os.path.join(C.OUT_REPORT, 'fit.csv'),
                  csv_text(['skel', 'class', 'axis', 'level', 'parent', 'rings', 'stock_rings', 'length_m',
                            'r_base_m', 'max_fit_err_m', 'p99_stock_to_tube_m', 'p99_to_cform_m', 'climbable_share',
                            'flags'], rows), crlf=False)
    C.atomic_text(os.path.join(C.OUT_REPORT, 'skeletons.csv'),
                  csv_text(['skel', 'kinds', 'class', 'species', 'header_flags', 'axes', 'level0', 'level1',
                            'level2_cards', 'rings', 'patch_tris', 'cards', 'bytes', 'patch_area_share',
                            'ring_fit_err_p99_m', 'gate_p99_m', 'gate_world_p99_m', 'collision_to_wood_p99_m',
                            'climbable_share', 'climb_tol_m', 'gate', 'crown_cell_m', 'crown_hulls',
                            'crown_clipped_share', 'second_opinion'], srows), crlf=False)
    write_readme(plan, res)
    print(f'summary: {len(res)} skeletons, {len(rows)} axis rows')


def write_readme(plan, res):
    ok = {s: r for s, r in res.items() if not r.get('error')}
    err = [s for s, r in res.items() if r.get('error')]
    kinds = sorted({k for r in ok.values() for k in r['kinds']})
    members = sorted({m for s in ok for m in plan[s]['members']})
    proc = [s for s, r in ok.items() if r['procedural']]
    total_bytes = sum(r['bytes'] for r in ok.values())
    L = []
    L.append('# Tree skeletons (WP1) - fit report')
    L.append('')
    L.append('Generated by `tools/trees/skeleton/build.py` (format: `tools/trees/FORMAT.md`). Per-skeleton sheets '
             f'(stock wood, rings, patches, fit heat map, collision, crown field) are in `{C.REPORT_PNG}`; '
             '`fit.csv` has one row per stock axis, `skeletons.csv` one row per skeleton, `../skel_index.json` maps '
             'every kind and exact member key to its skeleton.')
    L.append('')
    L.append('## Totals')
    L.append('')
    L.append(f'- Skeleton files: **{len(ok)}** (`gamedata/meshes/da/trees/<skel>.dtsk`, {total_bytes / 1048576:.1f} MB), '
             f'of them procedural (`p<kind>`): {len(proc)}; failed: {len(err)}{(" (" + ", ".join(err) + ")") if err else ""}.')
    L.append(f'- Kinds covered: {len(kinds)} inventory families = {len(members)} exact content keys '
             f'(TREE alive/dead/broken and BUSH_KEPT_STOCK).')
    ax = collections.Counter()
    for r in ok.values():
        ax['level0'] += r['axes_level0']
        ax['level1'] += r['axes_level1']
        ax['level2'] += r['axes_level2']
        ax['rings'] += r['rings']
        ax['rings_stock'] += r['rings_stock']
        ax['patch_tris'] += r['patch_tris']
        ax['patch_bark'] += r['patch_tris_bark']
        ax['cards'] += r['cards']
    L.append(f'- Axes: {ax["level0"]} level 0, {ax["level1"]} level 1 (modelled limbs), {ax["level2"]} level 2 '
             f'(card branches); rings {ax["rings"]} ({ax["rings_stock"]} on stock axes); cards {ax["cards"]}; '
             f'patch triangles {ax["patch_tris"]} ({ax["patch_bark"]} bark, the rest cut-end caps).')
    L.append('')
    # gate by class
    L.append('## CFORM gate (p99 distance of the visible refit wood to tree_trunk collision on climbable wood; limit 3 cm)')
    L.append('')
    L.append('In model space and in world space (each placement\'s distances times its scale). In world space the bar '
             'is the stock wood\'s own p99 distance to its collision where that is above 3 cm already (placements '
             'scaled up about three times put the stock trunk itself that far off its collision).')
    L.append('')
    L.append('| class | skeletons | with collision | pass | fail | p99 median | p99 max | world p99 max | '
             'collision->wood p99 median |')
    L.append('|---|---|---|---|---|---|---|---|---|')
    by = collections.defaultdict(list)
    for s, r in ok.items():
        by[cls_of(r)].append(r)
    for cl in sorted(by):
        rs = by[cl]
        gs = [r.get('gate') or {} for r in rs]
        p = [g['p99'] for g in gs if g.get('p99') is not None]
        wp = [g['world_p99'] for g in gs if g.get('world_p99') is not None]
        rv = [g['reverse_p99'] for g in gs if g.get('reverse_p99') is not None]
        npass = sum(1 for g in gs if g.get('p99') is not None and gate_word(g) == 'pass')
        L.append(f'| {cl} | {len(rs)} | {len(p)} | {npass} | {len(p) - npass} | '
                 f'{(100 * np.median(p)) if p else 0:.2f} cm | {(100 * max(p)) if p else 0:.2f} cm | '
                 f'{(100 * max(wp)) if wp else 0:.2f} cm | {(100 * np.median(rv)) if rv else 0:.2f} cm |')
    L.append('')
    L.append('Procedural kinds (BUSH_KEPT_STOCK) have no solid collision (passable hull only) and no stock wood '
             'constraint; they are outside the gate. Kinds without trunk collision in the sampled placements (separate '
             'collision hulls the visual does not touch) have no climbable wood and no gate value.')
    tight = collections.Counter((r.get('gate') or {}).get('climb_tol') for r in ok.values() if not r['procedural'])
    L.append('')
    L.append('Patch tolerance on climbable wood needed for the gate: ' + ', '.join(
        f'{"shape tolerance" if k is None else "%g cm" % (100 * k)}: {n}' for k, n in sorted(tight.items(), key=lambda t: (t[0] is not None, t[0] or 0))) + '.')
    L.append('')
    # patch share
    stock = [r for r in ok.values() if not r['procedural'] and 'patch_area_share' in r]
    area = sum(r['bark_area'] for r in stock)
    parea = sum(r['bark_area'] * r['patch_area_share'] for r in stock)
    shares = np.array([r['patch_area_share'] for r in stock]) if stock else np.zeros(1)
    L.append('## Patches (original triangles kept where the refit misses by more than 2 cm or 5 % of r)')
    L.append('')
    L.append(f'- Bark area kept as patches: **{100 * parea / max(area, 1e-9):.1f} %** of {area:.0f} m2 '
             f'(per skeleton p50 {100 * np.percentile(shares, 50):.1f} %, p90 {100 * np.percentile(shares, 90):.1f} %, '
             f'max {100 * shares.max():.1f} %). All cut-end caps are patches too.')
    hist = np.histogram(shares, bins=[0, 0.05, 0.1, 0.2, 0.4, 0.7, 1.0001])[0]
    L.append('- Skeletons by patch share: ' + ', '.join(f'{a}-{b} %: {n}' for (a, b), n in
                                                        zip([(0, 5), (5, 10), (10, 20), (20, 40), (40, 70), (70, 100)], hist)))
    L.append('')
    L.append('Why stock triangles stay: the contract allows a profile of k <= 3 harmonics per ring and a tolerance of '
             '2 cm or 5 % of r. A regular n-gon is met by a round tube no better than +-r(1 - cos(pi/n))/2 (6.7 % r '
             'for hexagons), so 6-sided stock trunks thicker than about 0.45 m (the 43 m pines and spruces), the '
             'coarse sculpted trunks and limbs of the generic deciduous, dead and anomalous kinds (irregular 5-15-gon '
             'trunks of 0.5-1 m, 3-4-sided limbs; one stock triangle often spans metres, so one miss keeps all of it) '
             'and the lobed or buttressed old oaks cannot be refit inside the tolerance: their stock triangles stay, '
             'the tubes (and so the axes the new branches grow on) run inside them. Forks and crotches, flared '
             'bases and cut ends account for most of the rest. Rings whose `fit_err` is above the tolerance mark '
             'where the patches carry the shape.')
    L.append('')
    weighted = [(r, plan[r['skel']]['placements']) for r in stock]
    tot_pl = sum(w for _, w in weighted)
    wsh = sum(r['patch_area_share'] * w for r, w in weighted) / max(tot_pl, 1)
    L.append(f'- Placement-weighted mean patch share (what a player sees): {100 * wsh:.1f} %.')
    so = [v for r in ok.values() for v in (r.get('second_opinion') or [])]
    if so:
        ch = collections.Counter(v['chosen'] for v in so)
        def before(key):
            vals = [v['levelsets'][key] for v in so if v['chosen'] != 'levelsets']
            return float(np.mean(vals)) if vals else 0.0
        L.append(f'- Second opinion on {len(so)} wood pieces more than half patched by the hop-level reading '
                 f'(geodesic contours; the voxel skeleton too where under 70 % of the vertices lie on clean stock '
                 f'rings): contours chosen for {ch.get("contour", 0)}, the voxel skeleton for {ch.get("voxel", 0)}, '
                 f'the hop levels kept for {ch.get("levelsets", 0)}. Where a second reading won, the stock surface within '
                 f'max(35 % r, 3 cm) of a tube went from {100 * before("covered"):.0f} % to '
                 f'{100 * np.mean([v[v["chosen"]]["covered"] for v in so if v["chosen"] != "levelsets"]):.0f} % and '
                 f'the tube surface out in the air from {100 * before("air"):.1f} % to '
                 f'{100 * np.mean([v[v["chosen"]]["air"] for v in so if v["chosen"] != "levelsets"]):.1f} %.')
    cr = [r.get('crown') or {} for r in ok.values()]
    used = sum(1 for c in cr if c.get('hulls_used'))
    clip = [c.get('clipped_area_share', 0) for c in cr if c.get('hulls_used')]
    L.append(f'- Crown fields: {sum(1 for c in cr if c)} with cards; clipped by a passable hull: {used} '
             f'(opaque card area outside the hull + 0.75 m: median {100 * (np.median(clip) if clip else 0):.1f} %, '
             f'max {100 * (max(clip) if clip else 0):.1f} %).')
    L.append('')
    L.append('## Worst cases')
    L.append('')
    L.append('| skeleton | kinds | class | patch area | ring fit_err p99 | gate p99 | world p99 |')
    L.append('|---|---|---|---|---|---|---|')
    worst = sorted(stock, key=lambda r: -max(r['patch_area_share'], ((r.get('gate') or {}).get('p99') or 0) / 0.03))
    for r in worst[:20]:
        g = r.get('gate') or {}
        L.append(f'| `{r["skel"]}` | {", ".join(r["kinds"][:3])} | {cls_of(r)} | {100 * r["patch_area_share"]:.1f} % | '
                 f'{100 * (r.get("fit_err_p99") or 0):.1f} cm | '
                 f'{"-" if g.get("p99") is None else "%.2f cm" % (100 * g["p99"])} | '
                 f'{"-" if g.get("world_p99") is None else "%.2f cm" % (100 * g["world_p99"])} |')
    L.append('')
    if err:
        L.append('## Errors')
        L.append('')
        for s in err:
            L.append(f'- `{s}`: ' + res[s]['error'].strip().splitlines()[-1])
        L.append('')
    C.atomic_text(os.path.join(C.OUT_REPORT, 'README.md'), '\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
